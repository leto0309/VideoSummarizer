"""Regenerate requirements.lock and requirements-gpu.lock from the direct requirements files.

Run on Windows x64 with CPython 3.11 (the platform the portable and source editions use):

    python scripts/lock_requirements.py

pip resolves the complete dependency set (dry run, nothing is installed). Each pinned
version then lists the SHA256 of every PyPI file this platform could install, plus the
source archive, so pip --require-hashes accepts exactly those files.
"""
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
LOCKS = {'requirements.txt': 'requirements.lock', 'requirements-gpu.txt': 'requirements-gpu.lock'}
# srt is published only as a source archive; the portable build turns it into a wheel.
SOURCE_ONLY = ('srt',)
HEADER = ('# Generated by scripts/lock_requirements.py from {source}; do not edit by hand.\n'
          '# Every package is pinned with the SHA256 of its PyPI files for Windows x64 / CPython 3.11.\n')


def resolve(requirements):
    """Return [(name, version, selected sha256)] for the full dependency set."""
    with tempfile.TemporaryDirectory() as folder:
        report = Path(folder) / 'report.json'
        subprocess.run([sys.executable, '-m', 'pip', 'install', '--dry-run', '--ignore-installed', '--quiet',
                        '--disable-pip-version-check', '--only-binary=:all:',
                        *[f'--no-binary={name}' for name in SOURCE_ONLY],
                        '--report', str(report), '-r', str(requirements)], check=True)
        items = json.loads(report.read_text(encoding='utf-8'))['install']
    return [(item['metadata']['name'], item['metadata']['version'],
             item['download_info'].get('archive_info', {}).get('hashes', {}).get('sha256')) for item in items]


def pypi_files(name, version):
    url = f'https://pypi.org/pypi/{name}/{version}/json'
    with urllib.request.urlopen(urllib.request.Request(url, headers={'Accept': 'application/json'}),
                                timeout=60) as response:
        return [{'filename': f['filename'], 'sha256': f['digests']['sha256'], 'yanked': f.get('yanked', False)}
                for f in json.load(response)['urls']]


def installable(files, supported):
    """Keep the source archive and wheels whose tags this interpreter supports."""
    from packaging.utils import parse_wheel_filename
    hashes = []
    for file in files:
        if file['yanked']:
            continue
        if file['filename'].endswith('.whl'):
            if not set(parse_wheel_filename(file['filename'])[3]) & supported:
                continue
        elif not file['filename'].endswith(('.tar.gz', '.zip')):
            continue
        hashes.append(file['sha256'])
    return sorted(set(hashes))


def render(entries, source):
    from packaging.utils import canonicalize_name
    lines = [HEADER.format(source=source)]
    for name, version, hashes in sorted(entries, key=lambda entry: canonicalize_name(entry[0])):
        lines.append(f'{canonicalize_name(name)}=={version} \\\n'
                     + ' \\\n'.join(f'    --hash=sha256:{value}' for value in hashes) + '\n')
    return ''.join(lines)


def lock(source, target, fetch=pypi_files):
    from packaging.tags import sys_tags
    supported = set(sys_tags())
    entries = []
    for name, version, selected in resolve(ROOT / source):
        hashes = installable(fetch(name, version), supported)
        if selected and selected not in hashes:
            raise RuntimeError(f'{name} {version}: the file pip selected is not among the PyPI hashes')
        if not hashes:
            raise RuntimeError(f'{name} {version}: no installable PyPI file for this platform')
        entries.append((name, version, hashes))
    (ROOT / target).write_bytes(render(entries, source).encode('utf-8'))
    return entries


def main():
    if sys.platform != 'win32' or sys.version_info[:2] != (3, 11) or sys.maxsize <= 2**32:
        raise SystemExit('Run on Windows x64 with CPython 3.11, the platform the release uses.')
    for source, target in LOCKS.items():
        entries = lock(source, target)
        print(f'{target}: {len(entries)} packages', flush=True)


if __name__ == '__main__':
    main()
