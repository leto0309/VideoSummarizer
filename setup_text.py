"""Setup, installer and launcher messages in Simplified Chinese, Traditional Chinese and English.

Standard library only: these messages are shown before the Python dependencies (and OpenCC) are installed.
The language is the page-language preference, which the first-run window lets the user choose.
The Traditional column must equal i18n.normalize(simplified, 'zh-TW'); tests check this.
"""
import json
import os
from pathlib import Path
import tempfile

ROOT = Path(__file__).resolve().parent
SETTINGS = ROOT / 'language-settings.json'
LANGUAGES = ('zh-CN', 'zh-TW', 'en')
DEFAULT_LANGUAGE = 'zh-CN'
# Set by the native window for the processes it starts, so a choice applies before it is saved.
ENVIRONMENT = 'VIDEOSUMMARIZER_LANGUAGE'


def language():
    value = os.environ.get(ENVIRONMENT)
    if value in LANGUAGES:
        return value
    try:
        value = json.loads(SETTINGS.read_text(encoding='utf-8')).get('ui_language')
    except (OSError, ValueError, AttributeError):
        value = None
    return value if value in LANGUAGES else DEFAULT_LANGUAGE


def save_language(value):
    """Store the page language chosen in the first-run window; the summary language keeps its setting."""
    if value not in LANGUAGES:
        raise ValueError(value)
    try:
        data = json.loads(SETTINGS.read_text(encoding='utf-8'))
        summary = data.get('summary_language') if isinstance(data, dict) else None
    except (OSError, ValueError):
        summary = None
    record = {'ui_language': value, 'summary_language': summary if summary in (*LANGUAGES, 'follow') else 'follow'}
    # Same atomic write as preferences.save, which the page uses for this file.
    fd, name = tempfile.mkstemp(prefix='.language-', suffix='.tmp', dir=SETTINGS.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as handle:
            json.dump(record, handle)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(name, SETTINGS)
    finally:
        Path(name).unlink(missing_ok=True)


def t(key, **values):
    return TEXT[key][LANGUAGES.index(language())].format(**values)


